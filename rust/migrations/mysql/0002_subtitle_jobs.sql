CREATE TABLE IF NOT EXISTS subtitle_job (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  show_id BIGINT UNSIGNED NOT NULL,
  show_storage_id BIGINT UNSIGNED NOT NULL,
  season_number INT UNSIGNED NOT NULL,
  episode_number INT UNSIGNED NOT NULL,
  languages_json LONGTEXT NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  provider_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  output_path VARCHAR(1024) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  locked_until DATETIME(3) NULL,
  claim_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  write_started_at DATETIME(3) NULL,
  error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_subtitle_job_episode (show_storage_id, season_number, episode_number),
  KEY idx_subtitle_job_queue (status, next_attempt_at, id),
  KEY idx_subtitle_job_show (show_id, created_at),
  CONSTRAINT chk_subtitle_job_status CHECK (status IN ('pending', 'processing', 'completed', 'skipped', 'failed', 'uncertain')),
  CONSTRAINT chk_subtitle_job_numbers CHECK (season_number > 0 AND episode_number > 0),
  CONSTRAINT chk_subtitle_job_attempts CHECK (attempt_count >= 0),
  CONSTRAINT fk_subtitle_job_show FOREIGN KEY (show_id) REFERENCES shows(id) ON DELETE CASCADE,
  CONSTRAINT fk_subtitle_job_storage FOREIGN KEY (show_storage_id) REFERENCES show_storage(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
